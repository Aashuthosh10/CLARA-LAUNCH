def localized(lang: str) -> dict:
    if lang == "en":
        return {uid: {**row} for uid, row in EN.items()}
    out = {}
    for uid, en_row in EN.items():
        loc = LOCALIZED[lang][uid]
        out[uid] = {
            **en_row,
            **loc,
            "image": None,
        }
    return out


def main() -> None:
    for lang in ("en", "kn", "hi", "ta", "te", "ml"):
        path = ROOT / f"{lang}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        campus = data.setdefault("campus_units", {})
        for key in list(campus.keys()):
            if key.startswith("events."):
                del campus[key]
        campus.update(localized(lang))
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print("updated", lang)


if __name__ == "__main__":
    main()
