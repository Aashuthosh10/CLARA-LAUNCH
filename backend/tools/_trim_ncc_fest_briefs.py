        data = json.loads(path.read_text(encoding="utf-8"))
        campus = data.setdefault("campus_units", {})
        for uid, by_lang in CONTENT.items():
            row = by_lang[lang]
            campus[uid] = {
                "title": row["title"],
                "supporting_line": row["supporting_line"],
                "points": list(row["points"]),
                "body": "",
                "tts_summary": row["tts_summary"],
                "image": None,
            }
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print("updated", lang)


