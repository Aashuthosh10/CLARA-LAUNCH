def main() -> None:
    for lang, block in NCC.items():
        path = LOCALES / f"{lang}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        campus = data.get("campus_units")
        if not isinstance(campus, dict):
            campus = {}
        for key in list(campus.keys()):
            if key.startswith("ncc."):
                del campus[key]
        campus.update(block)
        data["campus_units"] = campus
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(lang, sorted(k for k in campus if k.startswith("ncc.")))

    ui = json.loads(UI.read_text(encoding="utf-8"))
    for lang, text in ENROLL_UI.items():
        if lang == "ta":
            # Tamil UI copy lives in templates.py; do not create a partial ta bucket.
            continue
        if lang not in ui:
            continue
        bucket = ui[lang]
        ncc = bucket.setdefault("ncc", {})
        ncc["enrollment"] = text
        cards = bucket.setdefault("cards", {})
        cards["ncc"] = CARD_NCC[lang]
    UI.write_text(json.dumps(ui, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("ui.json updated")


if __name__ == "__main__":
    main()
